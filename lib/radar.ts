// Pulse Radar's model: one sealed snapshot in, one ranked board out.
//
// The board ranks every pre-token protocol the snapshot can rank: the 40 watchlist slugs (the
// floor, never the ceiling) plus every other pre-token protocol that is not an exchange, not a
// versioned pool, and not a wrapped, staked or bridged product of a token that already trades. Protocols whose token already trades are kept apart as the live reference set:
// the board never mixes the market's own value with a model's claim.
//
// Implied value is anchored in the snapshot's own market, not in a fixed multiple:
//
//   anchor     = median(mcap_usd / tvl_usd) over the live-token protocols of the same category
//                (at least 3 samples, else the global median over all live-token protocols),
//                clamped to [0.03, 1.20] so one outlier category cannot set the price
//   momentum   = 1 + clamp(change_7d, -50, 100) / 100 x 0.6
//   maturity   = 0.70 + min(age_days, 1095) / 1095 x 0.30   (age unknown: 365 days)
//   breadth    = 1 + 0.04 x min(chains - 1, 5)              (multi-chain reach, capped at 1.20)
//   implied    = max(1, round(tvl_usd x anchor x momentum x maturity x breadth))
//
// A category whose live tokens trade at 0.34x TVL prices its pre-token siblings higher than a
// category whose live tokens trade at 0.03x TVL: the market's own verdict on that kind of protocol,
// read from the same snapshot. No protocol name is ever special-cased; the same function scores
// every row, and the dashboard's Model tab shows the anchor table the run computed.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

